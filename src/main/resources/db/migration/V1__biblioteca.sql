create table rol (
    nombre varchar(20) primary key
);
insert into rol values ('ADMIN'), ('USUARIO');

create table usuario (
    id bigint generated by default as identity primary key,
    nombre varchar(120) not null,
    email varchar(254) not null unique,
    clave_hash varchar(100) not null
);
create table usuario_rol (
    usuario_id bigint not null references usuario(id),
    rol_nombre varchar(20) not null references rol(nombre),
    primary key (usuario_id, rol_nombre)
);
create table libro (
    id bigint generated by default as identity primary key,
    isbn varchar(13) not null unique,
    titulo varchar(200) not null,
    autor varchar(150) not null,
    total integer not null check (total > 0),
    disponibles integer not null check (disponibles between 0 and total)
);
create table prestamo (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null references usuario(id),
    libro_id bigint not null references libro(id),
    prestado_en timestamp with time zone not null,
    vence_en timestamp with time zone not null,
    devuelto_en timestamp with time zone,
    check (vence_en > prestado_en),
    check (devuelto_en is null or devuelto_en >= prestado_en)
);
create index idx_prestamo_usuario on prestamo(usuario_id, id);
create index idx_prestamo_libro on prestamo(libro_id);
